"""Build one static DocC website for the runtime and both authoring packages.

This entry point owns its marked output directory. Failed builds leave no site
to upload; conversion and static transformation take place in temporary staging.
SwiftPM compiler caches are reused, while public symbol graphs are refreshed.
"""

import argparse
import json
from pathlib import Path
import shlex
import shutil
import subprocess
import sys
import tempfile

import build_docc


PACKAGES = (".", "Packages/DiscordDSLMacros", "Packages/DiscordDSLExtensions")
MARKER = ".discordkit-documentation-site"
MARKER_CONTENT = "Generated by Tools/ci/build_documentation_site.py\n"
ROOT_REDIRECT = """<!doctype html>
<html lang="en">
<head><meta charset="utf-8"><title>DiscordKit Documentation</title>
<meta http-equiv="refresh" content="0; url=documentation/"></head>
<body><a href="documentation/">Open DiscordKit documentation</a></body>
</html>
"""


def run(command, repository):
    """Print and execute literal arguments, streaming strict failures to CI."""
    command = list(map(str, command))
    print("+ " + shlex.join(command), flush=True)
    subprocess.run(command, cwd=repository, check=True)


def prepare_output(output):
    """Remove an earlier owned export; never recursively delete arbitrary paths."""
    if output.is_symlink():
        raise ValueError(f"Documentation output must not be a symbolic link: {output}")
    if not output.exists():
        return
    marker = output / MARKER
    if (not output.is_dir() or marker.is_symlink() or not marker.is_file()
            or marker.read_text() != MARKER_CONTENT):
        raise ValueError(f"Refusing to replace unmarked documentation output: {output}")
    shutil.rmtree(output)


def build_site(repository, output, docc, hosting_base_path):
    """Refresh, check, convert and merge all public modules before static export."""
    repository = repository.resolve()
    # Keep a final-component symlink visible to the output ownership check.
    output = output.absolute()
    if (hosting_base_path and not hosting_base_path.startswith("/")) or any(
            value in hosting_base_path for value in ("?", "#", "\\", "..")):
        raise ValueError("hosting base path must be an absolute URL path without queries or traversal")
    prepare_output(output)
    output.parent.mkdir(parents=True, exist_ok=True)
    scripts = repository / "Tools/ci"
    with tempfile.TemporaryDirectory(prefix="documentation-site-", dir=output.parent) as temporary:
        staging = Path(temporary)
        archives = []
        for number, relative in enumerate(PACKAGES):
            package = repository / relative
            graphs = package / ".build/out/symbolgraph"
            if graphs.is_symlink():
                raise ValueError(f"Symbol graph output must not be a symbolic link: {graphs}")
            # Remove only generated graph files, retaining SwiftPM's build cache.
            for graph in graphs.glob("*.symbols.json"):
                graph.unlink()
            run(["swift", "package", "--package-path", package, "--force-resolved-versions",
                 "dump-symbol-graph", "--minimum-access-level", "public"], repository)
            run([sys.executable, scripts / "curate_docc.py", "--repository", package,
                 "--symbolgraphs", graphs, "--check"], repository)
            if number == 0:
                run([sys.executable, scripts / "documentation_examples.py", "--repository", package],
                    repository)
            converted = staging / f"package-{number}"
            run([sys.executable, scripts / "build_docc.py", "--repository", package,
                 "--symbolgraphs", graphs, "--output", converted, "--docc", docc], repository)
            report = json.loads((converted / "build-report.json").read_text())
            if report["failedModules"] or report["mergeStatus"] != "succeeded":
                raise ValueError(f"Incomplete DocC conversion: {package}")
            # Use the converter's explicit public scope, excluding its premerged archive.
            for module in report["modules"]:
                archive = converted / f"{module}.doccarchive"
                if not archive.is_dir():
                    raise ValueError(f"Missing converted public-module archive: {archive}")
                archives.append(archive)
        merged = staging / "DiscordKitLibrary.doccarchive"
        run(build_docc.merge_command(docc, archives, merged), repository)
        site = staging / "site"
        run([docc, "process-archive", "transform-for-static-hosting", merged,
             "--output-path", site, "--hosting-base-path", hosting_base_path], repository)
        if not (site / "documentation/index.html").is_file():
            raise ValueError("DocC did not produce the static documentation landing page")
        (site / "index.html").write_text(ROOT_REDIRECT)
        (site / ".nojekyll").touch()
        (site / MARKER).write_text(MARKER_CONTENT)
        site.rename(output)
    print(f"Built {len(archives)} public-module archives into {output}", flush=True)


def main():
    """Select the installed DocC and build a ready-to-upload GitHub Pages tree."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repository", type=Path, default=Path(__file__).resolve().parents[2])
    parser.add_argument("--output", type=Path, default=Path(".build/documentation-site"))
    parser.add_argument("--hosting-base-path", default="/DiscordKit")
    parser.add_argument("--docc", default=shutil.which("docc"))
    arguments = parser.parse_args()
    if not arguments.docc and shutil.which("xcrun"):
        arguments.docc = subprocess.check_output(["xcrun", "--find", "docc"], text=True).strip()
    if not arguments.docc:
        parser.error("docc is not installed; select a Swift toolchain with DocC")
    build_site(arguments.repository, arguments.output, arguments.docc, arguments.hosting_base_path)


if __name__ == "__main__":
    main()

def stable_symbol_hash(identifier):
    """Return DocC's FNV-1, folded-24-bit, base-36 precise-identifier hash.

    This is the public-domain FNV-1 algorithm used by Swift DocC's
    ``String+Hashing.swift``. It permits exact overload links without depending
    on an existing archive or unstable symbol-graph ordering.
    """
    value = 2166136261
    for byte in identifier.encode("utf-8"):
        value = ((value * 16777619) & 0xFFFFFFFF) ^ byte
    value = (value >> 24) ^ (value & 0xFFFFFF)
    result = ""
    while value:
        value, remainder = divmod(value, 36)
        result = "0123456789abcdefghijklmnopqrstuvwxyz"[remainder] + result
    return result or "0"


def owned_symbol(symbol, module):
    """Select explicit public declarations belonging to this module's source.

    Inherited synthesized declarations and extension nodes for foreign types
    are omitted. A location under ``Sources/<module>`` is authoritative; the
    Swift module mangling handles graphs whose compiler omits locations.
    """
    identifier = symbol["identifier"]["precise"]
    if "::SYNTHESIZED::" in identifier or symbol["kind"]["identifier"] == "swift.extension":
        return False
    if symbol.get("accessLevel", "public") not in {"public", "open"}:
        return False
    location = symbol.get("location", {}).get("uri")
    if location:
        parts = Path(unquote(urlparse(location).path)).parts
        return any(parts[index:index + 2] == ("Sources", module) for index in range(len(parts) - 1))
    return identifier.startswith(f"s:{len(module)}{module}")


def symbol_sort_key(symbol):
    """Sort by user-visible qualified spelling and then precise identity."""
    return (tuple(component.casefold() for component in symbol["pathComponents"]),
            tuple(symbol["pathComponents"]), symbol["identifier"]["precise"])


def symbol_path(symbol, module):
    """Build a module-qualified path, including the foreign extension namespace."""
    components = list(symbol["pathComponents"])
    extended = symbol.get("swiftExtension", {}).get("extendedModule")
    if extended and extended != module:
        components.insert(0, extended)
    return (module, *components)


def link_paths(symbols, module, relationships=()):
    """Resolve collision-safe links for all graph symbols, including inherited ones.

    Counting every graph declaration ensures an explicit member is still
    disambiguated when its otherwise identical name is inherited. DocC accepts
    the precise hash even when its presentation chooses an unhashed canonical
    path for a protocol requirement or a preferred declaration.

    Default implementations are documented beside their requirement, including
    when a refining protocol supplies the implementation. Their compiler-emitted
    path can name the refining protocol, so relationship-based paths must be
    resolved before collision counting rather than copied from pathComponents.
    Missing external requirements retain the available graph path.
    """
    paths = {identifier: symbol_path(symbol, module) for identifier, symbol in symbols.items()}
    default_paths = defaultdict(set)
    for relation in relationships:
        source, target = relation["source"], relation["target"]
        if relation["kind"] == "defaultImplementationOf" and source in paths and target in paths:
            default_paths[source].add((*paths[target][:-1], paths[source][-1]))
    for identifier, candidates in default_paths.items():
        if len(candidates) != 1:
            raise ValueError(f"Multiple default implementation paths for {identifier}")
        paths[identifier] = next(iter(candidates))
    groups = defaultdict(list)
    for symbol in symbols.values():
        if symbol["kind"]["identifier"] != "swift.extension":
            groups[paths[symbol["identifier"]["precise"]]].append(symbol)
    links = {}
    for path, candidates in groups.items():
        for symbol in candidates:
            identifier = symbol["identifier"]["precise"]
            suffix = f"-{stable_symbol_hash(identifier)}" if len(candidates) > 1 else ""
            links[identifier] = "/".join(path) + suffix
    return links


def readable_name(name):
    """Expand source-file camel case while preserving acronyms such as HTTP."""
    name = name.removesuffix(".generated")
    name = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1 \2", name)
    return re.sub(r"([a-z0-9])([A-Z])", r"\1 \2", name)


def reference_group(symbol, module, use_source_groups):
    """Choose source-domain navigation for large catalogs and kind for small ones."""
    if symbol["kind"]["identifier"] == "swift.macro":
        return "Authoring macros"
    kind = TYPE_KINDS.get(symbol["kind"]["identifier"], "Functions and variables")
    if not use_source_groups:
        return kind
    filename = Path(unquote(urlparse(symbol.get("location", {}).get("uri", "")).path)).stem
    if not filename or filename == module:
        return kind
    if module in {"DiscordModels", "DiscordHTTP"}:
        for prefixes, title in DOMAINS:
            if filename.startswith(prefixes):
                return title
    return readable_name(filename)


def topic_sections(groups, order=None):
    """Render nonempty DocC task groups with deterministic section and link order."""
    if not groups:
        return []
    names = order if order is not None else sorted(groups, key=str.casefold)
    lines = ["## Topics", ""]
    for name in names:
        if name not in groups:
            continue
        lines.extend([f"### {name}", ""])
        lines.extend(f"- ``{link}``" for link in groups[name])
        lines.append("")
    return lines


def reference_files(module, graphs):
    """Return relative generated filenames, contents and exact curation counts.

    Parent relationships determine nesting rather than name-prefix guesses.
    Default implementations receive their own group; protocol requirements keep
    their method/property group. External extension members remain navigable in
    the index without being misreported as types owned by this package.
    """
    symbols = {}
    relationships = []
    for graph in graphs:
        if graph.get("module", {}).get("name") != module:
            raise ValueError(f"Symbol graph does not belong to {module}")
        for symbol in graph["symbols"]:
            identifier = symbol["identifier"]["precise"]
            if identifier in symbols and symbols[identifier] != symbol:
                raise ValueError(f"Conflicting graph declarations for {identifier}")
            symbols[identifier] = symbol
        relationships.extend(graph["relationships"])
    owned = {identifier: symbol for identifier, symbol in symbols.items() if owned_symbol(symbol, module)}
    types = {identifier: symbol for identifier, symbol in owned.items()
             if symbol["kind"]["identifier"] in TYPE_KINDS}
    parents = {}
    defaults = set()
    for relation in relationships:
        if relation["kind"] in {"memberOf", "requirementOf", "optionalRequirementOf"}:
            source, target = relation["source"], relation["target"]
            if source in parents and parents[source] != target:
                raise ValueError(f"Multiple declaration parents for {source}")
            parents[source] = target
        elif relation["kind"] == "defaultImplementationOf":
            defaults.add(relation["source"])
    for relation in relationships:
        if relation["kind"] == "defaultImplementationOf" and relation["source"] not in parents:
            requirement_parent = parents.get(relation["target"])
            if requirement_parent is not None:
                parents[relation["source"]] = requirement_parent
    links = link_paths(symbols, module, relationships)
    children = defaultdict(list)
    top_level = []
    extensions = []
    for identifier, symbol in owned.items():
        parent = parents.get(identifier)
        if parent in types:
            children[parent].append(symbol)
        elif len(symbol["pathComponents"]) == 1:
            top_level.append(symbol)
        elif symbol.get("swiftExtension", {}).get("extendedModule") not in {None, module}:
            extensions.append(symbol)
        else:
            raise ValueError(f"Owned declaration has no owned parent: {identifier}")
    files = {}
    index_groups = defaultdict(list)
    for symbol in sorted(top_level, key=symbol_sort_key):
        group = reference_group(symbol, module, len(types) > 25)
        index_groups[group].append(links[symbol["identifier"]["precise"]])
    extension_containers = set()
    for symbol in extensions:
        path = symbol_path(symbol, module)
        extension_containers.update("/".join(path[:length]) for length in range(2, len(path)))
    index_groups["Extensions to standard library types"].extend(sorted(extension_containers))
    for symbol in sorted(extensions, key=symbol_sort_key):
        index_groups["Extensions to standard library types"].append(links[symbol["identifier"]["precise"]])
    if not index_groups["Extensions to standard library types"]:
        del index_groups["Extensions to standard library types"]
    lines = ["# API Reference", "",
             f"Browse the public types and operations provided by {module}.", ""]
    lines.extend(topic_sections(index_groups))
    lines.extend([GENERATED, ""])
    files[Path("APIReference.md")] = "\n".join(lines).rstrip() + "\n"
    member_count = 0
    for identifier, symbol in sorted(types.items(), key=lambda pair: symbol_sort_key(pair[1])):
        groups = defaultdict(list)
        for child in sorted(children[identifier], key=symbol_sort_key):
            child_id = child["identifier"]["precise"]
            kind = child["kind"]["identifier"]
            group = "Default implementations" if child_id in defaults else MEMBER_KINDS.get(kind)
            if group is None:
                raise ValueError(f"Unrecognized member kind {kind} for {child_id}")
            groups[group].append(links[child_id])
            member_count += 1
        lines = [f"# ``{links[identifier]}``", ""]
        lines.extend(topic_sections(groups, [*MEMBER_KINDS.values(), "Default implementations"]))
        lines.extend(["## See Also", "", "- <doc:APIReference>"])
        if parents.get(identifier) in types:
            lines.append(f"- ``{links[parents[identifier]]}``")
        lines.extend(["", GENERATED, ""])
        filename = Path("Reference") / (".".join(symbol["pathComponents"]) + ".md")
        if filename in files:
            raise ValueError(f"Type reference filename collision: {filename}")
        files[filename] = "\n".join(lines).rstrip() + "\n"
    return files, {"module": module, "typePages": len(types), "memberLinks": member_count,
                   "topLevelLinks": len(top_level), "externalExtensionLinks": len(extensions)}


def synchronize(catalog, expected, write=False):
    """Check or update only generated navigation, preserving unrelated catalog files.

    Returns changed relative filenames. Check mode performs no mutations. Write
    mode refuses to overwrite or remove an unmarked file so authored content
    cannot be accidentally replaced when a declaration changes.
    """
    existing = set((catalog / "Reference").glob("*.md")) if (catalog / "Reference").is_dir() else set()
    if (catalog / "APIReference.md").exists():
        existing.add(catalog / "APIReference.md")
    stale = existing - {catalog / path for path in expected}
    differences = []
    for relative, contents in sorted(expected.items()):
        path = catalog / relative
        current = path.read_text() if path.exists() else None
        if current == contents:
            continue
        differences.append(str(relative))
        if write:
            if current is not None and GENERATED not in current:
                raise ValueError(f"Refusing to overwrite authored documentation: {path}")
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(contents)
    for path in sorted(stale):
        differences.append(str(path.relative_to(catalog)))
        if write:
            if GENERATED not in path.read_text():
                raise ValueError(f"Refusing to remove authored documentation: {path}")
            path.unlink()
    return differences


def main():
    """Curate actual library modules only and fail checks on missing or stale pages."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repository", type=Path, default=Path(__file__).resolve().parents[2])
    parser.add_argument("--symbolgraphs", type=Path, default=Path(".build/out/symbolgraph"))
    parser.add_argument("--module", action="append", help="Limit to named public library modules")
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    repository = arguments.repository.resolve()
    modules = build_docc.public_modules(repository)
    if arguments.module:
        unknown = set(arguments.module) - set(modules)
        if unknown:
            parser.error("Not public library modules: " + ", ".join(sorted(unknown)))
        modules = sorted(set(arguments.module))
    directory = arguments.symbolgraphs.resolve()
    reports = []
    differences = []
    for module in modules:
        graphs = [json.loads(path.read_text()) for path in build_docc.module_graphs(directory, module)]
        expected, report = reference_files(module, graphs)
        catalog = repository / "Sources" / module / f"{module}.docc"
        changes = synchronize(catalog, expected, write=arguments.write)
        differences.extend(f"{module}/{path}" for path in changes)
        reports.append(report)
    print(json.dumps({"moduleCount": len(modules), "typePages": sum(report["typePages"] for report in reports),
                      "memberLinks": sum(report["memberLinks"] for report in reports),
                      "modules": reports, "changedFiles": len(differences)}, indent=2))
    if differences and arguments.check:
        raise SystemExit("DocC reference navigation is stale; run --write:\n" + "\n".join(differences))


if __name__ == "__main__":
    main()

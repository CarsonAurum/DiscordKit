"""Maintain DocC reference navigation from public, owned Swift symbol graphs.

Run SwiftPM's public ``dump-symbol-graph`` first, then use ``--write`` to refresh
the committed navigation or ``--check`` to detect drift without modifying files.
Declaration comments remain the source of API descriptions and contracts. This
tool only adds Topics and See Also sections; it never replaces their abstracts.
"""


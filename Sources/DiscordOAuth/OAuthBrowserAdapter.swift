import DiscordCore
import Foundation

/// A host-owned browser presentation request. Formatting conceals the authorization URL,
/// whose state and PKCE challenge must not enter logs. No client secret is accepted.
public struct OAuthBrowserRequest: Sendable, CustomStringConvertible, CustomDebugStringConvertible, CustomReflectable {
    public let authorizationURL: URL
    public let callbackScheme: String
    public let prefersEphemeralSession: Bool

    /// Validates the fixed Discord authorization origin and the host callback scheme.
    /// - Parameters:
    ///   - authorizationURL: Exact URL generated by `OAuthAuthorizationFlow`; only HTTPS
    ///     `discord.com/oauth2/authorize`, without credentials, port or fragment, is allowed;
    ///     the complete URL is bounded to 64 KiB of UTF-8 metadata.
    ///   - callbackScheme: Registered URI scheme without a colon, 1...128 ASCII characters.
    ///     The host adapter owns application registration and universal-link policy.
    ///   - prefersEphemeralSession: Host UI preference, default true; actual OS support
    ///     and consent behavior belong to the injected adapter.
    /// - Throws: `DiscordError.validation(.invalidValue)` for an unsafe origin or scheme.
    public init(authorizationURL: URL, callbackScheme: String, prefersEphemeralSession: Bool = true) throws {
        guard authorizationURL.absoluteString.utf8.count <= 65_536,
              authorizationURL.scheme == "https", authorizationURL.host == "discord.com",
              authorizationURL.path == "/oauth2/authorize", authorizationURL.user == nil,
              authorizationURL.password == nil, authorizationURL.port == nil,
              authorizationURL.fragment == nil, !callbackScheme.isEmpty,
              callbackScheme.utf8.count <= 128,
              callbackScheme.utf8.first.map({ (65...90).contains($0) || (97...122).contains($0) }) == true,
              callbackScheme.utf8.allSatisfy({ (65...90).contains($0) || (97...122).contains($0)
                  || (48...57).contains($0) || [43, 45, 46].contains($0) })
        else { throw DiscordError.validation(.invalidValue) }
        self.authorizationURL = authorizationURL
        self.callbackScheme = callbackScheme
        self.prefersEphemeralSession = prefersEphemeralSession
    }

    /// Conceals browser query values from normal diagnostics.
    public var description: String { "OAuthBrowserRequest(redacted)" }
    /// Conceals browser query values from debug diagnostics.
    public var debugDescription: String { description }
    /// Prevents recursive reflection from exposing the authorization URL.
    public var customMirror: Mirror { Mirror(self, children: ["redacted": true]) }
}

/// Host presentation failures deliberately contain no provider/OS error text or URL.
public enum OAuthBrowserFailure: Error, Sendable, Equatable {
    case presentationFailed
}

/// Injects browser UI independently of OAuth token exchange, transport and secure storage.
/// Construction starts no session. Presentation runs on the main actor; the application
/// owns its OS session, presentation anchor and cancellation cleanup. This adapter never
/// exchanges a code or supplies a confidential client secret to a public application.
public struct OAuthBrowserAdapter: Sendable {
    private let present: @MainActor @Sendable (OAuthBrowserRequest) async throws -> URL

    /// Stores an application-supplied OS browser operation without running it.
    /// - Parameter present: Main-actor UI operation returning the exact callback URL.
    ///   It must dismiss and release the OS session on completion and cancellation,
    ///   avoid logging sensitive URLs, and never follow the callback as a web request.
    public init(present: @escaping @MainActor @Sendable (OAuthBrowserRequest) async throws -> URL) {
        self.present = present
    }

    /// Presents consent and validates the callback through its one-use flow owner.
    /// - Parameters:
    ///   - flow: Expected redirect, state, issuer and PKCE owner; each successful callback
    ///     consumes it once, including when browser presentation completes concurrently.
    ///   - callbackScheme: OS-registered scheme matching the flow's redirect URI.
    ///   - prefersEphemeralSession: Host UI preference, default true.
    /// - Returns: Validated code or explicitly selected legacy implicit token; no exchange occurs.
    /// - Throws: Cancellation before/after presentation; validation or OAuth callback failures;
    ///   `OAuthBrowserFailure.presentationFailed` replaces arbitrary host error text.
    ///   A cancelled presentation does not consume a callback. A presentation that ignores
    ///   cancellation can delay return; host adapters must cooperate with cancellation.
    public func authorize(flow: OAuthAuthorizationFlow, callbackScheme: String,
                          prefersEphemeralSession: Bool = true) async throws -> OAuthAuthorizationResult {
        try Task.checkCancellation()
        guard flow.redirectURI.scheme?.lowercased() == callbackScheme.lowercased()
        else { throw DiscordError.validation(.invalidValue) }
        let request = try OAuthBrowserRequest(authorizationURL: flow.authorizationURL,
            callbackScheme: callbackScheme, prefersEphemeralSession: prefersEphemeralSession)
        let callback: URL
        do { callback = try await present(request) }
        catch is CancellationError { throw CancellationError() }
        catch { throw OAuthBrowserFailure.presentationFailed }
        try Task.checkCancellation()
        return try await flow.consumeCallback(callback)
    }
}

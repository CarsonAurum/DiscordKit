/// Published MLS working-group suite-2 vectors and adversarial primitive/ratchet checks.
@Suite struct MLSCryptoTests {
    /// Loads pinned, offline suite-2 fixtures, failing if packaging or JSON structure changes.
    /// - Parameter name: Fixture base name without the `suite2-` prefix or `.json` suffix.
    /// - Returns: Published cases retaining exact upstream field values.
    /// - Throws: File, JSON, or test-requirement failures; never performs network access.
    private func vectors(_ name: String) throws -> [[String: Any]] {
        let url = try #require(Bundle.module.url(forResource: "suite2-" + name, withExtension: "json", subdirectory: "Fixtures"))
        return try #require(JSONSerialization.jsonObject(with: Data(contentsOf: url)) as? [[String: Any]])
    }

    /// Parses trusted fixture hex while asserting complete pairs and valid digits.
    /// - Parameter value: Even-length lowercase hexadecimal fixture text.
    /// - Returns: Exact bytes, including an empty value for empty text.
    /// - Throws: Test-requirement failures on malformed fixture content.
    private func hex(_ value: String) throws -> Data {
        let bytes = Array(value.utf8); try #require(bytes.count.isMultiple(of: 2))
        var output = Data()
        for index in stride(from: 0, to: bytes.count, by: 2) {
            let text = String(decoding: bytes[index...index + 1], as: UTF8.self)
            output.append(try #require(UInt8(text, radix: 16)))
        }
        return output
    }

    /// Reads a named hexadecimal field from a published fixture dictionary.
    /// - Parameters:
    ///   - object: Fixture object containing the field.
    ///   - key: Expected hexadecimal field name.
    /// - Returns: Exact decoded fixture bytes.
    /// - Throws: Test-requirement failures for missing, mistyped, or malformed fields.
    private func bytes(_ object: [String: Any], _ key: String) throws -> Data {
        try hex(#require(object[key] as? String))
    }

    /// Verifies independent published KDF, reference hash, signature, and HPKE open vectors.
    /// The expected values are imported from mlswg, never generated by this implementation.
    @Test func publishedCryptoBasics() throws {
        let fixture = try #require(vectors("crypto-basics").first)
        let expand = try #require(fixture["expand_with_label"] as? [String: Any])
        #expect(try MLSCipherSuite2.expandWithLabel(secret: bytes(expand, "secret"), label: #require(expand["label"] as? String), context: bytes(expand, "context"), length: #require(expand["length"] as? Int)) == bytes(expand, "out"))
        let derive = try #require(fixture["derive_secret"] as? [String: Any])
        #expect(try MLSCipherSuite2.deriveSecret(bytes(derive, "secret"), label: #require(derive["label"] as? String)) == bytes(derive, "out"))
        let tree = try #require(fixture["derive_tree_secret"] as? [String: Any])
        #expect(try MLSCipherSuite2.deriveTreeSecret(bytes(tree, "secret"), label: #require(tree["label"] as? String), generation: UInt32(#require(tree["generation"] as? UInt64)), length: #require(tree["length"] as? Int)) == bytes(tree, "out"))
        let ref = try #require(fixture["ref_hash"] as? [String: Any])
        #expect(try MLSCipherSuite2.refHash(label: #require(ref["label"] as? String), value: bytes(ref, "value")) == bytes(ref, "out"))
        let sign = try #require(fixture["sign_with_label"] as? [String: Any])
        #expect(try MLSCipherSuite2.verifyWithLabel(publicKey: bytes(sign, "pub"), label: #require(sign["label"] as? String), content: bytes(sign, "content"), signature: bytes(sign, "signature")))
        let encrypt = try #require(fixture["encrypt_with_label"] as? [String: Any])
        let encrypted = try MLSHPKECiphertext(kemOutput: bytes(encrypt, "kem_output"), ciphertext: bytes(encrypt, "ciphertext"))
        #expect(try MLSCipherSuite2.decryptWithLabel(privateKey: bytes(encrypt, "priv"), label: #require(encrypt["label"] as? String), context: bytes(encrypt, "context"), encrypted: encrypted) == bytes(encrypt, "plaintext"))
    }

    /// Verifies all five chained epochs, Welcome branches, exporters and deterministic P-256
    /// external-key derivation against independent published working-group expected bytes.
    @Test func publishedKeySchedule() throws {
        let fixture = try #require(vectors("key-schedule").first)
        var previous = try bytes(fixture, "initial_init_secret")
        for epoch in try #require(fixture["epochs"] as? [[String: Any]]) {
            let schedule = try MLSKeySchedule(initSecret: previous, commitSecret: bytes(epoch, "commit_secret"), pskSecret: bytes(epoch, "psk_secret"), groupContext: bytes(epoch, "group_context"))
            #expect(schedule.joinerSecret == (try bytes(epoch, "joiner_secret")))
            #expect(schedule.welcomeSecret == (try bytes(epoch, "welcome_secret")))
            #expect(schedule.initSecret == (try bytes(epoch, "init_secret")))
            #expect(schedule.senderDataSecret == (try bytes(epoch, "sender_data_secret")))
            #expect(schedule.encryptionSecret == (try bytes(epoch, "encryption_secret")))
            #expect(schedule.exporterSecret == (try bytes(epoch, "exporter_secret")))
            #expect(schedule.externalSecret == (try bytes(epoch, "external_secret")))
            #expect(schedule.confirmationKey == (try bytes(epoch, "confirmation_key")))
            #expect(schedule.membershipKey == (try bytes(epoch, "membership_key")))
            #expect(schedule.resumptionPSK == (try bytes(epoch, "resumption_psk")))
            #expect(schedule.epochAuthenticator == (try bytes(epoch, "epoch_authenticator")))
            #expect(try MLSCipherSuite2.deriveHPKEKeyPair(schedule.externalSecret).publicKey == bytes(epoch, "external_pub"))
            let exporter = try #require(epoch["exporter"] as? [String: Any])
            #expect(try schedule.export(label: #require(exporter["label"] as? String), context: bytes(exporter, "context"), length: #require(exporter["length"] as? Int)) == bytes(exporter, "secret"))
            let joining = try MLSKeySchedule(joinerSecret: schedule.joinerSecret, pskSecret: bytes(epoch, "psk_secret"), groupContext: bytes(epoch, "group_context"))
            #expect(joining.epochSecret == schedule.epochSecret)
            let initial = try MLSKeySchedule(epochSecret: schedule.epochSecret)
            #expect(initial.epochAuthenticator == schedule.epochAuthenticator)
            #expect(initial.joinerSecret.isEmpty && initial.welcomeSecret.isEmpty)
            previous = schedule.initSecret
        }
    }

    /// Verifies 1-, 8- and 32-leaf tree vectors, independent ratchets and sender-data derivation.
    /// Generations 0 and 15 exercise repeated hash-ratchet advancement and skipped keys.
    @Test func publishedSecretTree() throws {
        for fixture in try vectors("secret-tree") {
            let leaves = try #require(fixture["leaves"] as? [[[String: Any]]])
            var tree = try MLSSecretTree(encryptionSecret: bytes(fixture, "encryption_secret"), leafCount: leaves.count, maximumSkippedKeys: 65536)
            for (leaf, generations) in leaves.enumerated() {
                for generation in generations {
                    let index = UInt32(try #require(generation["generation"] as? UInt64))
                    for kind in [MLSSecretTree.RatchetKind.application, .handshake] {
                        let material = try tree.consume(leaf: leaf, kind: kind, generation: index)
                        #expect(material.key == (try bytes(generation, kind.rawValue + "_key")))
                        #expect(material.nonce == (try bytes(generation, kind.rawValue + "_nonce")))
                        #expect(material.generation == index)
                    }
                }
            }
            let sender = try #require(fixture["sender_data"] as? [String: Any])
            let sample = try Data(bytes(sender, "ciphertext").prefix(32))
            #expect(try MLSCipherSuite2.expandWithLabel(secret: bytes(sender, "sender_data_secret"), label: "key", context: sample, length: 16) == bytes(sender, "key"))
            #expect(try MLSCipherSuite2.expandWithLabel(secret: bytes(sender, "sender_data_secret"), label: "nonce", context: sample, length: 12) == bytes(sender, "nonce"))
        }
    }

    /// Exercises fresh signature and HPKE generation, exact label/context binding, malformed
    /// points, truncation and tampering; only fully authenticated plaintext can be returned.
    @Test func signatureAndHPKEFailures() throws {
        let signing = P256.Signing.PrivateKey()
        let content = Data("private test content".utf8)
        let signature = try MLSCipherSuite2.signWithLabel(privateKey: signing.rawRepresentation, label: "test", content: content)
        #expect(try MLSCipherSuite2.verifyWithLabel(publicKey: signing.publicKey.x963Representation, label: "test", content: content, signature: signature))
        #expect(try !MLSCipherSuite2.verifyWithLabel(publicKey: signing.publicKey.x963Representation, label: "other", content: content, signature: signature))
        #expect(try !MLSCipherSuite2.verifyWithLabel(publicKey: signing.publicKey.x963Representation, label: "test", content: content + Data([0]), signature: signature))
        #expect(try !MLSCipherSuite2.verifyWithLabel(publicKey: Data(), label: "test", content: content, signature: signature))
        #expect(try !MLSCipherSuite2.verifyWithLabel(publicKey: signing.publicKey.x963Representation, label: "test", content: content, signature: Data([0])))
        #expect(throws: MLSError.invalidConfiguration) { try MLSCipherSuite2.signWithLabel(privateKey: Data(), label: "test", content: content) }
        let pair = try MLSCipherSuite2.deriveHPKEKeyPair(Data(repeating: 7, count: 32))
        let context = Data([1, 2, 3])
        let encrypted = try MLSCipherSuite2.encryptWithLabel(publicKey: pair.publicKey, label: "test", context: context, plaintext: content)
        #expect(try MLSCipherSuite2.decryptWithLabel(privateKey: pair.privateKey, label: "test", context: context, encrypted: encrypted) == content)
        #expect(throws: MLSError.authenticationFailed) { try MLSCipherSuite2.decryptWithLabel(privateKey: pair.privateKey, label: "other", context: context, encrypted: encrypted) }
        #expect(throws: MLSError.authenticationFailed) { try MLSCipherSuite2.decryptWithLabel(privateKey: pair.privateKey, label: "test", context: context + Data([0]), encrypted: encrypted) }
        var changed = encrypted.ciphertext; changed[changed.startIndex] ^= 1
        #expect(throws: MLSError.authenticationFailed) { try MLSCipherSuite2.decryptWithLabel(privateKey: pair.privateKey, label: "test", context: context, encrypted: MLSHPKECiphertext(kemOutput: encrypted.kemOutput, ciphertext: changed)) }
        for malformed in [MLSHPKECiphertext(kemOutput: Data(), ciphertext: encrypted.ciphertext), MLSHPKECiphertext(kemOutput: encrypted.kemOutput, ciphertext: Data())] {
            #expect(throws: MLSError.authenticationFailed) { try MLSCipherSuite2.decryptWithLabel(privateKey: pair.privateKey, label: "test", context: context, encrypted: malformed) }
        }
        #expect(throws: MLSError.invalidConfiguration) { try MLSCipherSuite2.encryptWithLabel(publicKey: Data(), label: "test", context: context, plaintext: content) }
        #expect(throws: MLSError.invalidConfiguration) { try MLSCipherSuite2.deriveHPKEKeyPair(Data()) }
        #expect(String(describing: pair) == "MLSHPKEKeyPair(<redacted>)")
        #expect(String(reflecting: pair) == "MLSHPKEKeyPair(<redacted>)")
        #expect(Mirror(reflecting: pair).children.count == 1)
        #expect(Mirror(reflecting: pair).children.first?.value as? String == "<redacted>")
    }

    /// Covers AES-GCM empty/full payloads, AAD tamper, invalid sizes and independent SHA/HMAC
    /// expected values so the common primitive wrappers are checked beyond local round trips.
    @Test func symmetricAndBounds() throws {
        #expect(MLSCipherSuite2.hash(Data()) == (try hex("e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855")))
        let key = Data(repeating: 0, count: 16), nonce = Data(repeating: 0, count: 12)
        let empty = try MLSCipherSuite2.seal(key: key, nonce: nonce, plaintext: Data(), authenticatedData: Data())
        #expect(empty == (try hex("58e2fccefa7e3061367f1d57a4e7455a")))
        #expect(try MLSCipherSuite2.open(key: key, nonce: nonce, ciphertext: empty, authenticatedData: Data()).isEmpty)
        let content = Data([1, 2, 3]), aad = Data([4, 5])
        let encrypted = try MLSCipherSuite2.seal(key: key, nonce: nonce, plaintext: content, authenticatedData: aad)
        #expect(encrypted.startIndex == 0)
        #expect(try MLSCipherSuite2.open(key: key, nonce: nonce, ciphertext: encrypted, authenticatedData: aad) == content)
        let prefixedKey = Data([9]) + key, prefixedNonce = Data([9]) + nonce
        let sliced = try MLSCipherSuite2.seal(key: prefixedKey.dropFirst(), nonce: prefixedNonce.dropFirst(), plaintext: (Data([9]) + content).dropFirst(), authenticatedData: (Data([9]) + aad).dropFirst())
        #expect(sliced == encrypted)
        #expect(try MLSCipherSuite2.open(key: prefixedKey.dropFirst(), nonce: prefixedNonce.dropFirst(), ciphertext: (Data([9]) + encrypted).dropFirst(), authenticatedData: aad) == content)
        for invalidKey in [Data(), Data(repeating: 0, count: 15), Data(repeating: 0, count: 17)] {
            #expect(throws: MLSError.invalidConfiguration) { try MLSCipherSuite2.seal(key: invalidKey, nonce: nonce, plaintext: content, authenticatedData: aad) }
            #expect(throws: MLSError.authenticationFailed) { try MLSCipherSuite2.open(key: invalidKey, nonce: nonce, ciphertext: encrypted, authenticatedData: aad) }
        }
        for invalidNonce in [Data(), Data(repeating: 0, count: 11), Data(repeating: 0, count: 13)] {
            #expect(throws: MLSError.invalidConfiguration) { try MLSCipherSuite2.seal(key: key, nonce: invalidNonce, plaintext: content, authenticatedData: aad) }
            #expect(throws: MLSError.authenticationFailed) { try MLSCipherSuite2.open(key: key, nonce: invalidNonce, ciphertext: encrypted, authenticatedData: aad) }
        }
        #expect(throws: MLSError.authenticationFailed) { try MLSCipherSuite2.open(key: key, nonce: nonce, ciphertext: encrypted, authenticatedData: Data()) }
        #expect(throws: MLSError.invalidConfiguration) { try MLSCipherSuite2.seal(key: Data(), nonce: nonce, plaintext: content, authenticatedData: aad) }
        #expect(throws: MLSError.authenticationFailed) { try MLSCipherSuite2.open(key: key, nonce: Data(), ciphertext: encrypted, authenticatedData: aad) }
        #expect(throws: MLSError.authenticationFailed) { try MLSCipherSuite2.open(key: key, nonce: nonce, ciphertext: Data([0]), authenticatedData: aad) }
        let hmac = MLSCipherSuite2.mac(key: Data(repeating: 0x0b, count: 20), content: Data("Hi There".utf8))
        #expect(hmac == (try hex("b0344c61d8db38535ca8afceaf0bf12b881dc200c9833da726e9376c2e32cff7")))
        #expect(MLSCipherSuite2.extract(salt: Data(repeating: 0x0b, count: 20), ikm: Data("Hi There".utf8)) == hmac)
        #expect(MLSCipherSuite2.verifyMAC(key: Data(repeating: 0x0b, count: 20), content: Data("Hi There".utf8), tag: hmac))
        #expect(!MLSCipherSuite2.verifyMAC(key: key, content: content, tag: hmac))
        #expect(!MLSCipherSuite2.verifyMAC(key: key, content: content, tag: Data()))
        let secret = Data(repeating: 0, count: 32)
        #expect(try MLSCipherSuite2.expandWithLabel(secret: secret, label: "", context: Data(), length: 0).isEmpty)
        #expect(try MLSCipherSuite2.expandWithLabel(secret: secret, label: "", context: Data(), length: 8160).count == 8160)
        for length in [-1, 8161, Int.max] {
            #expect(throws: MLSError.invalidConfiguration) { try MLSCipherSuite2.expandWithLabel(secret: secret, label: "", context: Data(), length: length) }
        }
        #expect(throws: MLSError.invalidConfiguration) { try MLSCipherSuite2.deriveSecret(Data(), label: "test") }
        #expect(throws: MLSError.invalidConfiguration) { try MLSKeySchedule(initSecret: Data(), commitSecret: secret, groupContext: Data()) }
        #expect(throws: MLSError.invalidConfiguration) { try MLSKeySchedule(initSecret: secret, commitSecret: Data(), groupContext: Data()) }
        #expect(throws: MLSError.invalidConfiguration) { try MLSKeySchedule(joinerSecret: Data(), groupContext: Data()) }
        #expect(throws: MLSError.invalidConfiguration) { try MLSKeySchedule(joinerSecret: secret, pskSecret: Data(), groupContext: Data()) }
        #expect(throws: MLSError.invalidConfiguration) { try MLSKeySchedule(epochSecret: Data()) }
        let schedule = try MLSKeySchedule(epochSecret: secret)
        #expect(try schedule.export(label: "test", context: content, length: 32) == schedule.export(label: Data("test".utf8), context: content, length: 32))
        #expect(String(describing: schedule) == "MLSKeySchedule(<redacted>)")
        #expect(String(reflecting: schedule) == "MLSKeySchedule(<redacted>)")
        #expect(Mirror(reflecting: schedule).children.first?.value as? String == "<redacted>")
        let oversized = Data(repeating: 0, count: 1_048_576)
        #expect(throws: MLSError.capacityExceeded) { try MLSCipherSuite2.expandWithLabel(secret: secret, label: "test", context: oversized, length: 16) }
        #expect(throws: MLSError.capacityExceeded) { try MLSCipherSuite2.refHash(label: "test", value: oversized) }
        let tooLarge = oversized + Data([0])
        #expect(throws: MLSError.invalidConfiguration) { try MLSCipherSuite2.seal(key: key, nonce: nonce, plaintext: tooLarge, authenticatedData: Data()) }
        #expect(throws: MLSError.invalidConfiguration) { try MLSCipherSuite2.seal(key: key, nonce: nonce, plaintext: Data(), authenticatedData: tooLarge) }
        #expect(throws: MLSError.authenticationFailed) { try MLSCipherSuite2.open(key: key, nonce: nonce, ciphertext: tooLarge + Data(repeating: 0, count: 16), authenticatedData: Data()) }
        #expect(throws: MLSError.authenticationFailed) { try MLSCipherSuite2.open(key: key, nonce: nonce, ciphertext: empty, authenticatedData: tooLarge) }
        #expect(throws: MLSError.invalidConfiguration) { try MLSCipherSuite2.deriveHPKEKeyPair(tooLarge) }
        let pair = try MLSCipherSuite2.deriveHPKEKeyPair(secret)
        #expect(throws: MLSError.invalidConfiguration) { try MLSCipherSuite2.encryptWithLabel(publicKey: pair.publicKey, label: "test", context: Data(), plaintext: tooLarge) }
        #expect(throws: MLSError.authenticationFailed) { try MLSCipherSuite2.decryptWithLabel(privateKey: pair.privateKey, label: "test", context: Data(), encrypted: MLSHPKECiphertext(kemOutput: pair.publicKey, ciphertext: tooLarge + Data(repeating: 0, count: 16))) }
    }

    /// Verifies single consumption, reordering, bound failures without mutation, leaf/kind
    /// independence and nonce guards. Copying is used only to check transactional rollback.
    @Test func secretTreeReorderingAndBounds() throws {
        let secret = Data(repeating: 8, count: 32)
        var tree = try MLSSecretTree(encryptionSecret: secret, leafCount: 8, maximumForwardDistance: 4, maximumSkippedKeys: 3)
        let first = try tree.next(leaf: 2, kind: .application)
        #expect(first.generation == 0)
        #expect(throws: MLSError.staleGeneration) { try tree.consume(leaf: 2, kind: .application, generation: 0) }
        let fourth = try tree.consume(leaf: 2, kind: .application, generation: 4)
        #expect(fourth.generation == 4 && tree.retainedSkippedKeyCount == 3)
        #expect(throws: MLSError.capacityExceeded) { try tree.consume(leaf: 3, kind: .application, generation: 1) }
        #expect(tree.retainedSkippedKeyCount == 3)
        let second = try tree.consume(leaf: 2, kind: .application, generation: 1)
        #expect(second.generation == 1 && tree.retainedSkippedKeyCount == 2)
        #expect(throws: MLSError.staleGeneration) { try tree.consume(leaf: 2, kind: .application, generation: 1) }
        #expect(throws: MLSError.capacityExceeded) { try tree.consume(leaf: 2, kind: .application, generation: 10) }
        let next = try tree.next(leaf: 2, kind: .application)
        #expect(next.generation == 5)
        let otherKind = try tree.next(leaf: 2, kind: .handshake)
        let otherLeaf = try tree.next(leaf: 3, kind: .application)
        #expect(otherKind.generation == 0 && otherLeaf.generation == 0)
        #expect(otherKind.key != first.key && otherLeaf.key != first.key)
        for leaf in [-1, 8, Int.max] {
            #expect(throws: MLSError.invalidConfiguration) { try tree.next(leaf: leaf, kind: .application) }
        }
        for leaves in [0, 3, 65537] {
            #expect(throws: MLSError.invalidConfiguration) { try MLSSecretTree(encryptionSecret: secret, leafCount: leaves) }
        }
        #expect(throws: MLSError.invalidConfiguration) { try MLSSecretTree(encryptionSecret: Data(), leafCount: 1) }
        #expect(throws: MLSError.invalidConfiguration) { try MLSSecretTree(encryptionSecret: secret, leafCount: 1, maximumForwardDistance: -1) }
        #expect(throws: MLSError.invalidConfiguration) { try MLSSecretTree(encryptionSecret: secret, leafCount: 1, maximumSkippedKeys: 65537) }
        let guarded = try first.guardedNonce(reuseGuard: Data([1, 2, 3, 4]))
        #expect(guarded.prefix(4) == Data(zip(first.nonce.prefix(4), [UInt8(1), 2, 3, 4]).map(^)))
        #expect(guarded.suffix(8) == first.nonce.suffix(8))
        #expect(throws: MLSError.invalidConfiguration) { try first.guardedNonce(reuseGuard: Data()) }
        #expect(!String(reflecting: first).contains(first.key.base64EncodedString()))
        #expect(String(reflecting: tree).contains("<redacted>"))
        #expect(Mirror(reflecting: tree).children.first?.value as? String == "<redacted>")
        #expect(Mirror(reflecting: first).children.first?.value as? String == "<redacted>")
        var sequential = try MLSSecretTree(encryptionSecret: secret, leafCount: 1, maximumForwardDistance: 0, maximumSkippedKeys: 0)
        #expect(throws: MLSError.capacityExceeded) { try sequential.consume(leaf: 0, kind: .application, generation: 1) }
        #expect(try sequential.next(leaf: 0, kind: .application).generation == 0)
        var limited = try MLSSecretTree(encryptionSecret: secret, leafCount: 1, maximumGeneration: 2)
        #expect(try limited.consume(leaf: 0, kind: .application, generation: 2).generation == 2)
        #expect(throws: MLSError.staleGeneration) { try limited.next(leaf: 0, kind: .application) }
        #expect(throws: MLSError.staleGeneration) { try limited.consume(leaf: 0, kind: .application, generation: 3) }
        #expect(try limited.consume(leaf: 0, kind: .application, generation: 0).generation == 0)
        #expect(try limited.next(leaf: 0, kind: .handshake).generation == 0)
    }

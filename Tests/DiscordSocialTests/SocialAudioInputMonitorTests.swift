import DiscordMedia
import Synchronization
import Testing
@testable import DiscordSocial

/// Records synchronous detector callbacks without tasks, sleeps or cross-actor races.
@available(macOS 15, iOS 18, tvOS 18, watchOS 11, visionOS 2, *)
private final class AudioInputObservations: Sendable {
    private let values = Mutex<[Bool]>([])

    /// Appends one callback observation under the finite test's sole shared lock.
    /// - Parameter value: New threshold-crossing detection state.
    func append(_ value: Bool) { values.withLock { $0.append(value) } }

    /// Returns the exact ordered callback history for assertions.
    /// - Returns: Copy of observations generated by explicitly processed fixture blocks.
    func snapshot() -> [Bool] { values.withLock { $0 } }
}

/// Deterministic no-input monitoring over routed normalized PCM; no native device/engine qualification is inferred.
@Suite struct SocialAudioInputMonitorTests {
    /// Published threshold bounds and disabled default remain explicit, while invalid construction fails safely.
    /// - Throws: Unexpected valid construction, PCM or actor-operation failures fail the test.
    @Test func thresholdBoundsAndDefault() async throws {
        let monitor = try SocialAudioInputMonitor()
        let full = try Self.buffer([1, -1])
        #expect(try await monitor.process(full) == nil)
        let initial = await monitor.snapshot()
        #expect(initial.thresholdDBFS == -100 && !initial.enabled && initial.inputDetected == nil && !initial.closed)
        for threshold in [-100.0, -99.999, -60, 0, 100] {
            let candidate = try SocialAudioInputMonitor(thresholdDBFS: threshold)
            let snapshot = await candidate.snapshot()
            #expect(snapshot.thresholdDBFS == threshold)
            #expect(snapshot.enabled == (threshold > -100))
            #expect(snapshot.inputDetected == nil && !snapshot.closed)
        }
        for threshold in [-Double.infinity, Double.infinity, .nan, -100.001, 100.001] {
            #expect(throws: MediaError.invalidThreshold) { try SocialAudioInputMonitor(thresholdDBFS: threshold) }
        }
    }

    /// Actual threshold changes clear the old baseline; identical/invalid changes preserve it atomically.
    /// Detection can be disabled and reenabled without generating fictitious microphone transitions.
    /// - Throws: Unexpected valid configuration or processing failures fail the test.
    @Test func thresholdReplacementAndReenable() async throws {
        let monitor = try SocialAudioInputMonitor(thresholdDBFS: 0)
        let silent = try Self.buffer([0, 0]), active = try Self.buffer([1, -1])
        #expect(try await monitor.process(silent) == nil)
        #expect(await monitor.snapshot().inputDetected == false)
        #expect(try await monitor.process(active) == true)
        try await monitor.setThreshold(0)
        #expect(await monitor.snapshot().inputDetected == true)
        for threshold in [-Double.infinity, Double.infinity, .nan, -101, 101] {
            await #expect(throws: MediaError.invalidThreshold) { try await monitor.setThreshold(threshold) }
            #expect(await monitor.snapshot().thresholdDBFS == 0)
            #expect(await monitor.snapshot().inputDetected == true)
        }
        try await monitor.setThreshold(-60)
        #expect(await monitor.snapshot().inputDetected == nil)
        #expect(try await monitor.process(silent) == nil)
        #expect(try await monitor.process(active) == true)
        try await monitor.setThreshold(-100)
        #expect(try await monitor.process(silent) == nil)
        #expect(await monitor.snapshot().inputDetected == nil)
        #expect(!(await monitor.snapshot().enabled))
        try await monitor.setThreshold(-60)
        #expect(try await monitor.process(active) == nil)
        #expect(await monitor.snapshot().inputDetected == true)
    }

    /// Callbacks fire once per transition, with registration replacement/removal and no initial/replayed event.
    /// Returned transitions remain useful when no callback is registered.
    /// - Throws: Unexpected valid observer, threshold or PCM operations fail the test.
    @available(macOS 15, iOS 18, tvOS 18, watchOS 11, visionOS 2, *)
    @Test func transitionCallbacks() async throws {
        let first = AudioInputObservations(), second = AudioInputObservations()
        let monitor = try SocialAudioInputMonitor(thresholdDBFS: -60, callback: { first.append($0) })
        let silent = try Self.buffer([0]), active = try Self.buffer([0.5])
        #expect(try await monitor.process(active) == nil)
        #expect(first.snapshot().isEmpty)
        #expect(try await monitor.process(silent) == false)
        #expect(try await monitor.process(silent) == nil)
        #expect(try await monitor.process(active) == true)
        #expect(first.snapshot() == [false, true])
        try await monitor.setCallback(nil)
        #expect(try await monitor.process(silent) == false)
        #expect(first.snapshot() == [false, true])
        try await monitor.setCallback { second.append($0) }
        #expect(second.snapshot().isEmpty)
        #expect(try await monitor.process(active) == true)
        #expect(first.snapshot() == [false, true])
        #expect(second.snapshot() == [true])
        try await monitor.setThreshold(-40)
        #expect(try await monitor.process(silent) == nil)
        #expect(second.snapshot() == [true])
        #expect(try await monitor.process(active) == true)
        #expect(second.snapshot() == [true, true])
    }

    /// All-channel RMS avoids opposite-polarity cancellation, differs from peak detection and handles zeros,
    /// subnormals, empty input and the largest bounded stereo block without retaining any sample storage.
    /// - Throws: Unexpected valid PCM construction or monitoring failures fail the test.
    @Test func rmsStereoEmptyAndExtremeSamples() async throws {
        let stereo = try SocialAudioInputMonitor(thresholdDBFS: -1)
        #expect(try await stereo.process(Self.buffer([0, 0], channels: 2)) == nil)
        #expect(try await stereo.process(Self.buffer([1, -1], channels: 2)) == true)
        #expect(try await stereo.process(Self.buffer([], channels: 2)) == nil)
        #expect(await stereo.snapshot().inputDetected == true)
        let rms = try SocialAudioInputMonitor(thresholdDBFS: -2)
        #expect(try await rms.process(Self.buffer([1, -1])) == nil)
        #expect(try await rms.process(Self.buffer([1, 0])) == false)
        try await rms.setThreshold(100)
        #expect(try await rms.process(Self.buffer([1, -1])) == nil)
        #expect(await rms.snapshot().inputDetected == false)
        try await rms.setThreshold(-99)
        #expect(try await rms.process(Self.buffer([Float.leastNonzeroMagnitude, -Float.leastNonzeroMagnitude])) == nil)
        #expect(await rms.snapshot().inputDetected == false)
        let format = try PCMFormat(sampleRate: 192_000, channelCount: 2)
        let largest = try PCMBuffer(format: format, samples: .init(repeating: 1, count: 192_000 * 120 / 1000 * 2))
        #expect(try await rms.process(largest) == true)
    }

    /// Close is terminal, clears baseline/observer ownership and rejects every mutating/processing operation.
    /// - Throws: Unexpected valid construction or pre-close processing failures fail the test.
    @Test func closureIsTerminal() async throws {
        let monitor = try SocialAudioInputMonitor(thresholdDBFS: -20)
        let active = try Self.buffer([1])
        #expect(try await monitor.process(active) == nil)
        await monitor.close(); await monitor.close()
        let snapshot = await monitor.snapshot()
        #expect(snapshot.closed && !snapshot.enabled && snapshot.inputDetected == nil && snapshot.thresholdDBFS == -20)
        await #expect(throws: MediaError.closed) { try await monitor.process(active) }
        await #expect(throws: MediaError.closed) { try await monitor.setThreshold(-100) }
        await #expect(throws: MediaError.closed) { try await monitor.setCallback(nil) }
    }

    /// Builds one short normalized PCM fixture without any device, clock or codec dependency.
    /// - Parameters:
    ///   - samples: Interleaved mono/stereo finite values in -1...1; empty input is permitted.
    ///   - channels: One by default, or two for stereo fixtures; sample count must contain whole frames.
    /// - Returns: Bounded 48 kHz PCM.
    /// - Throws: Existing PCM format, alignment, normalization or duration validation errors.
    private static func buffer(_ samples: [Float], channels: Int = 1) throws -> PCMBuffer {
        try PCMBuffer(format: PCMFormat(channelCount: channels), samples: samples)
    }
}

/// Stable author-facing errors; messages never include a submitted interaction or runtime value.
private struct AuthoringDiagnostic: DiagnosticMessage {
    let message: String
    let diagnosticID: MessageID
    let severity: DiagnosticSeverity = .error

    /// Creates one deterministic compiler diagnostic in the package-owned namespace.
    /// - Parameters:
    ///   - id: Stable machine-readable suffix, independent of source positions.
    ///   - message: Finite explanation of the authoring restriction and recovery.
    init(_ id: String, _ message: String) {
        self.message = message
        diagnosticID = MessageID(domain: "DiscordDSLMacros", id: id)
    }
}

/// Fully syntactic field metadata; imported types are retained verbatim for Swift to check.
private struct ArgumentField {
    let name: String
    let type: String
    let optionName: String
    let description: String
    let fallback: String?
    let source: String
}

/// Shared finite syntax admission; none of these helpers resolves symbols, reads files or executes code.
enum AuthoringSyntax {
    /// Emits a stable error anchored to the offending original syntax node.
    /// - Parameters:
    ///   - context: Compiler-owned expansion context receiving the diagnostic.
    ///   - node: Source node to underline; no external source is inspected.
    ///   - id: Stable error identity.
    ///   - message: Author-facing explanation and recovery hint.
    static func diagnose(_ context: some MacroExpansionContext, _ node: some SyntaxProtocol,
                         _ id: String, _ message: String) {
        context.diagnose(Diagnostic(node: Syntax(node), message: AuthoringDiagnostic(id, message)))
    }

    /// Extracts a literal's unescaped simple text for metadata validation.
    /// Interpolation and escapes are rejected deliberately so name/length checks are exact.
    /// - Parameter expression: Metadata expression from the original attribute.
    /// - Returns: Simple single-line literal contents, or nil for raw/multiline forms, escapes,
    ///   interpolation or expressions requiring evaluation. Swift remains the literal type checker.
    static func literal(_ expression: ExprSyntax) -> String? {
        guard let value = expression.as(StringLiteralExprSyntax.self), value.segments.count == 1,
              value.openingPounds == nil, value.openingQuote.text == "\"",
              case .stringSegment(let segment) = value.segments.first,
              !segment.content.text.contains("\\") else { return nil }
        return segment.content.text
    }

    /// Checks the documented conservative lowercase slash-name subset before runtime validation.
    /// - Parameter value: Unescaped metadata string, never invocation data.
    /// - Returns: Whether the name has 1...32 lowercase letter/number/underscore/hyphen scalars.
    static func validName(_ value: String) -> Bool {
        (1...32).contains(value.unicodeScalars.count) && value == value.lowercased()
            && value.unicodeScalars.allSatisfy {
                CharacterSet.letters.contains($0) || CharacterSet.decimalDigits.contains($0) || $0 == "_" || $0 == "-"
            }
    }

    /// Retains a source coordinate expression generated by the compiler without filesystem reads.
    /// - Parameters:
    ///   - node: Original declaration or field node whose location is retained.
    ///   - context: Compiler location authority.
    /// - Returns: An explicit runtime source initializer, with zero/empty fallback when unavailable.
    static func source(_ node: some SyntaxProtocol, _ context: some MacroExpansionContext) -> String {
        guard let location = context.location(of: node, at: .afterLeadingTrivia, filePathMode: .fileID) else {
            return ".init(fileID: \"\", line: 0, column: 0)"
        }
        return ".init(fileID: \(location.file), line: \(location.line), column: \(location.column))"
    }

    /// Resolves an attribute's final name token, accepting module-qualified macro references.
    /// - Parameters:
    ///   - attribute: Original attached attribute syntax.
    ///   - name: Desired unqualified macro identifier.
    /// - Returns: Whether its final syntactic component matches, without symbol lookup.
    static func isAttribute(_ attribute: AttributeSyntax, named name: String) -> Bool {
        attribute.attributeName.trimmedDescription.split(separator: ".").last == Substring(name)
    }

    /// Admits finite defaults without executing initializer calls or traversing imported source.
    /// - Parameter expression: Explicit property initializer.
    /// - Returns: True for scalar literals, nil, unary signed numbers and enum-member expressions.
    static func finiteDefault(_ expression: ExprSyntax) -> Bool {
        if expression.is(IntegerLiteralExprSyntax.self) || expression.is(FloatLiteralExprSyntax.self)
            || expression.is(BooleanLiteralExprSyntax.self) || expression.is(NilLiteralExprSyntax.self) {
            return true
        }
        if let literal = expression.as(StringLiteralExprSyntax.self) {
            return literal.segments.allSatisfy { if case .stringSegment = $0 { true } else { false } }
        }
        if let prefix = expression.as(PrefixOperatorExprSyntax.self) {
            return ["-", "+"].contains(prefix.operator.text)
                && (prefix.expression.is(IntegerLiteralExprSyntax.self) || prefix.expression.is(FloatLiteralExprSyntax.self))
        }
        if let member = expression.as(MemberAccessExprSyntax.self) {
            return member.base == nil || member.base?.is(DeclReferenceExprSyntax.self) == true
                || (member.base.map { finiteDefault($0) } ?? false)
        }
        return false
    }

    /// Rejects obvious built-in type/default mismatches while leaving custom types to Swift.
    /// - Parameters:
    ///   - expression: Already admitted finite fallback.
    ///   - type: Explicit field type spelling.
    /// - Returns: Whether the pair is obviously incompatible; aliases/custom codecs are not guessed.
    static func incompatibleDefault(_ expression: ExprSyntax, type: TypeSyntax) -> Bool {
        let spelling = type.trimmedDescription.replacingOccurrences(of: "Swift.", with: "")
        let optional = spelling.hasSuffix("?") || spelling.hasPrefix("Optional<")
        if expression.is(NilLiteralExprSyntax.self) { return !optional }
        let scalar = spelling.hasSuffix("?") ? String(spelling.dropLast()) : spelling
        switch scalar {
        case "String": return !expression.is(StringLiteralExprSyntax.self)
        case "Bool": return !expression.is(BooleanLiteralExprSyntax.self)
        case "Int", "Int64", "Double":
            return !(expression.is(IntegerLiteralExprSyntax.self) || expression.is(FloatLiteralExprSyntax.self)
                || expression.is(PrefixOperatorExprSyntax.self))
        default: return false
        }
    }

    /// Finds an explicit inherited protocol spelling without resolving imported declarations.
    /// - Parameters:
    ///   - declaration: Original struct declaration.
    ///   - name: Unqualified protocol name.
    /// - Returns: True when an inheritance-list component explicitly names the protocol.
    static func inherits(_ declaration: StructDeclSyntax, _ name: String) -> Bool {
        declaration.inheritanceClause?.inheritedTypes.contains {
            $0.type.trimmedDescription.split(separator: ".").last == Substring(name)
        } ?? false
    }

    /// Finds the supported explicitly spelled slash-handler response contracts without symbol lookup.
    /// - Parameter declaration: Original handler struct, including optional module-qualified inheritance.
    /// - Returns: Matching family names in stable order. No match retains the established manual default;
    ///   more than one requires an author diagnostic because response ownership must be exclusive.
    static func handlerFamilies(_ declaration: StructDeclSyntax) -> [String] {
        ["SlashCommandHandler", "ModalSlashCommandHandler", "DeferredSlashCommandHandler", "ManualSlashCommandHandler"].filter {
            inherits(declaration, $0)
        }
    }

    /// Validates the macro's supported root declaration and reserved generated names.
    /// - Parameters:
    ///   - declaration: Attached declaration group.
    ///   - reserved: Generated member identifiers that user members must not shadow.
    ///   - context: Diagnostic destination.
    /// - Returns: Supported nongeneric struct, or nil after an actionable diagnostic.
    static func structure(_ declaration: some DeclGroupSyntax, reserved: Set<String>,
                          context: some MacroExpansionContext) -> StructDeclSyntax? {
        guard let value = declaration.as(StructDeclSyntax.self), value.genericParameterClause == nil else {
            diagnose(context, declaration, "unsupported-declaration", "authoring macros require a nongeneric struct")
            return nil
        }
        for member in value.memberBlock.members {
            let names: [String]
            if let variable = member.decl.as(VariableDeclSyntax.self) {
                names = variable.bindings.compactMap { $0.pattern.as(IdentifierPatternSyntax.self)?.identifier.text }
            } else if let function = member.decl.as(FunctionDeclSyntax.self) { names = [function.name.text] }
            else { names = [] }
            if names.contains(where: reserved.contains) {
                diagnose(context, member, "reserved-member", "member conflicts with a macro-generated schema, command or contribution")
                return nil
            }
        }
        return value
    }

    /// Validates all instance fields and captures their exact finite descriptor inputs.
    /// - Parameters:
    ///   - declaration: Supported original argument struct.
    ///   - context: Diagnostic and source-location authority.
    /// - Returns: Ordered fields, or nil when any property cannot be safely decoded.
    fileprivate static func fields(_ declaration: StructDeclSyntax, context: some MacroExpansionContext) -> [ArgumentField]? {
        var fields: [ArgumentField] = []
        var names: Set<String> = []
        var valid = true
        for member in declaration.memberBlock.members {
            guard let variable = member.decl.as(VariableDeclSyntax.self) else { continue }
            let attributes = variable.attributes.compactMap { $0.as(AttributeSyntax.self) }
            let markers = attributes.filter { isAttribute($0, named: "Option") }
            if variable.modifiers.contains(where: { ["static", "class"].contains($0.name.text) }) {
                if !markers.isEmpty {
                    diagnose(context, variable, "unsupported-property", "@Option requires an instance stored property; static options are unsupported")
                    valid = false
                }
                continue
            }
            guard markers.count == 1 else {
                diagnose(context, variable, "missing-option", "every instance property requires exactly one @Option")
                valid = false; continue
            }
            guard variable.bindings.count == 1, let binding = variable.bindings.first,
                  let identifier = binding.pattern.as(IdentifierPatternSyntax.self),
                  let type = binding.typeAnnotation?.type, binding.accessorBlock == nil,
                  variable.modifiers.allSatisfy({ !["lazy", "weak", "unowned"].contains($0.name.text) }),
                  attributes.count == 1 else {
                diagnose(context, variable, "unsupported-property", "@Option requires one explicitly typed stored property without accessors or other wrappers")
                valid = false; continue
            }
            let name = identifier.identifier.text
            let plainName = name.replacingOccurrences(of: "`", with: "")
            guard plainName != "_discordValidated" else {
                diagnose(context, variable, "reserved-member", "property conflicts with the macro-generated _discordValidated initializer marker")
                valid = false; continue
            }
            guard case .argumentList(let arguments) = markers[0].arguments else {
                diagnose(context, markers[0], "literal-metadata", "@Option requires a literal description and optional literal name")
                valid = false; continue
            }
            var optionName = plainName
            var description: String?
            var descriptionExpression: String?
            var metadataValid = true
            var labels: Set<String> = []
            for argument in arguments {
                let label = argument.label?.text ?? ""
                guard ["name", "description"].contains(label), labels.insert(label).inserted else {
                    metadataValid = false; continue
                }
                if label == "name", argument.expression.is(NilLiteralExprSyntax.self) { continue }
                guard let literalValue = literal(argument.expression) else { metadataValid = false; continue }
                if label == "name" { optionName = literalValue }
                else { description = literalValue; descriptionExpression = argument.expression.trimmedDescription }
            }
            guard metadataValid, let description, let descriptionExpression,
                  (1...100).contains(description.unicodeScalars.count), validName(optionName) else {
                diagnose(context, markers[0], "literal-metadata", "@Option requires a valid literal name and 1...100 character literal description without escapes or interpolation")
                valid = false; continue
            }
            guard names.insert(optionName).inserted else {
                diagnose(context, variable, "duplicate-option", "duplicate Discord option name in @CommandArguments")
                valid = false; continue
            }
            if let initializer = binding.initializer {
                guard variable.bindingSpecifier.text != "let" else {
                    diagnose(context, variable, "initialized-let", "initialized let options cannot be decoded; use var for an explicit default")
                    valid = false; continue
                }
                guard finiteDefault(initializer.value) else {
                    diagnose(context, initializer, "dynamic-default", "option defaults must be finite scalar literals, nil or enum members; calls and interpolation are unsupported")
                    valid = false; continue
                }
                guard !incompatibleDefault(initializer.value, type: type) else {
                    diagnose(context, initializer, "incompatible-default", "option default is incompatible with its explicitly declared Swift type")
                    valid = false; continue
                }
            }
            fields.append(.init(name: name, type: type.trimmedDescription,
                optionName: StringLiteralExprSyntax(content: optionName).description,
                description: descriptionExpression, fallback: binding.initializer?.value.trimmedDescription,
                source: source(binding, context)))
        }
        if fields.count > 25 {
            diagnose(context, declaration, "option-limit", "@CommandArguments supports at most 25 options")
            valid = false
        }
        return valid ? fields : nil
    }
}

/// Generates explicit typed argument construction over the existing handwritten schema API.
public struct CommandArgumentsMacro: MemberMacro, ExtensionMacro {
    /// Emits a throwing schema accessor and private validated-value initializer without running either.
    /// - Parameters:
    ///   - node: Original attribute; arguments are intentionally unsupported.
    ///   - declaration: Nongeneric argument struct with marked instance fields.
    ///   - protocols: Compiler-requested conformances; generated schema semantics remain unchanged.
    ///   - context: Compiler diagnostics and source-coordinate provider.
    /// - Returns: Inert documented members, or no members after validation errors.
    /// - Throws: Syntax construction errors are propagated to the compiler; author errors are diagnostics.
    public static func expansion(of node: AttributeSyntax, providingMembersOf declaration: some DeclGroupSyntax,
                                 conformingTo protocols: [TypeSyntax], in context: some MacroExpansionContext) throws -> [DeclSyntax] {
        guard let structure = AuthoringSyntax.structure(declaration, reserved: ["schema"], context: context),
              let fields = AuthoringSyntax.fields(structure, context: context) else { return [] }
        let access = structure.modifiers.first(where: { ["public", "package"].contains($0.name.text) }).map { $0.name.text + " " } ?? ""
        let descriptors = fields.enumerated().map { index, field in
            "let option\(index) = try DiscordCommandDSL.ArgumentOption<\(field.type)>(name: \(field.optionName), description: \(field.description), defaultValue: \(field.fallback.map { ".value(\($0))" } ?? ".none"), source: \(field.source))"
        }.joined(separator: "\n")
        let options = fields.indices.map { "option\($0).erased" }.joined(separator: ", ")
        let values = fields.enumerated().map { "\($0.element.name): try decoder.value(for: option\($0.offset))" }.joined(separator: ", ")
        let schema = """
        /// Builds the ordered finite schema without tasks, I/O, registration or handler execution.
        /// Each descriptor is captured once; every invocation constructs fresh validated argument state.
        /// - Throws: Existing ArgumentDiagnostic errors for invalid registration, choices or defaults.
        \(access)static var schema: DiscordCommandDSL.CommandArgumentSchema<Self> {
            /// Validates inert descriptors and retains a synchronous invocation-local constructor.
            /// - Throws: ArgumentDiagnostic for invalid options, order, aggregate limits or defaults.
            get throws {
                \(descriptors)
                return try DiscordCommandDSL.CommandArgumentSchema(options: [\(options)], source: \(AuthoringSyntax.source(structure, context))) { decoder in
                    Self(_discordValidated: (), \(values))
                }
            }
        }
        """
        let parameters = fields.map { "\($0.name): \($0.type)" }.joined(separator: ", ")
        let assignments = fields.map { "self.\($0.name) = \($0.name)" }.joined(separator: "\n")
        let docs = fields.map { "///   - \($0.name): Exact typed value already validated and cached by the schema." }.joined(separator: "\n")
        let initializer = """
        /// Retains one complete invocation's validated values without codecs, work or resource ownership.
        /// - Parameters:
        ///   - _discordValidated: Private marker preventing collision with an author's ordinary initializer.
        \(docs)
        private init(_discordValidated: Void\(parameters.isEmpty ? "" : ", " + parameters)) {
            \(assignments)
        }
        """
        let schemaFixed = fields.isEmpty ? schema.replacingOccurrences(of: "Self(_discordValidated: (), )", with: "Self(_discordValidated: ())") : schema
        return [DeclSyntax(stringLiteral: schemaFixed), DeclSyntax(stringLiteral: initializer)]
    }

    /// Adds the runtime protocol only when it is not already explicitly inherited.
    /// - Parameters:
    ///   - node: Attached authoring attribute.
    ///   - declaration: Original declaration, inspected only for supported shape and inherited names.
    ///   - type: Compiler-qualified extended type, preserving nesting.
    ///   - protocols: Compiler-requested conformances; no semantic source resolution is attempted.
    ///   - context: Compiler-owned expansion context; this role emits no duplicate diagnostics.
    /// - Returns: One empty conformance extension or no extension for unsupported/already-conforming types.
    /// - Throws: SwiftSyntax construction errors, propagated to the compiler.
    public static func expansion(of node: AttributeSyntax, attachedTo declaration: some DeclGroupSyntax,
                                 providingExtensionsOf type: some TypeSyntaxProtocol, conformingTo protocols: [TypeSyntax],
                                 in context: some MacroExpansionContext) throws -> [ExtensionDeclSyntax] {
        guard let structure = declaration.as(StructDeclSyntax.self), structure.genericParameterClause == nil,
              !AuthoringSyntax.inherits(structure, "CommandArguments") else { return [] }
        return [try ExtensionDeclSyntax("extension \(type): DiscordCommandDSL.CommandArguments {}")]
    }
}

/// A pure marker: enclosing argument expansion owns all property validation and schema generation.
public struct OptionMacro: PeerMacro {
    /// Removes the marker without creating storage, observers, peers, tasks or runtime work.
    /// - Parameters:
    ///   - node: Original option marker.
    ///   - declaration: Property expected inside a marked argument struct.
    ///   - context: Compiler diagnostic authority.
    /// - Returns: Always empty, because the enclosing macro supplies the actual implementation.
    /// - Throws: This implementation never throws.
    public static func expansion(of node: AttributeSyntax, providingPeersOf declaration: some DeclSyntaxProtocol,
                                 in context: some MacroExpansionContext) throws -> [DeclSyntax] {
        guard declaration.is(VariableDeclSyntax.self) else {
            AuthoringSyntax.diagnose(context, declaration, "unsupported-property", "@Option requires a stored property")
            return []
        }
        guard let owner = context.lexicalContext.first(where: { !$0.is(VariableDeclSyntax.self) })?.as(StructDeclSyntax.self),
              owner.attributes.compactMap({ $0.as(AttributeSyntax.self) }).contains(where: {
                AuthoringSyntax.isAttribute($0, named: "CommandArguments")
            }) else {
            AuthoringSyntax.diagnose(context, node, "orphan-option", "@Option requires an enclosing @CommandArguments struct")
            return []
        }
        return []
    }
}

/// Compiler entry point listing only package-owned syntactic authoring macros.
@main
struct DiscordDSLMacrosPlugin: CompilerPlugin {
    /// Macro implementations loaded by the compiler host; constructing this list performs no runtime work.
    let providingMacros: [Macro.Type] = [CommandArgumentsMacro.self, OptionMacro.self, SlashCommandMacro.self, UserCommandMacro.self, MessageCommandMacro.self]
}
